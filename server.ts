// AI Chatbot endpoint
app.post("/api/chat", async (req, res) => {
  try {
    const { message, history } = req.body;
    if (!message) {
      return res.status(400).json({ error: "Message is required" });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      // Return smart tactical offline response if API key is not configured
      return res.json({
        reply: `[Штаб tDt]: Внимание, боец! Запрос принят. Напоминаю базовые директивы:\n- Минималка в Дуэли: 1,000,000 очков.\n- Задания Сокола держим на профильные дни (Среда и Пятница)!\n- Все ресурсы только в 1-й отряд (Артур, Марлена, Шэдоу, Синтия, Люциус).\n\nВаш вопрос: "${message}". Для персонального ИИ-анализа подключите API-ключ Gemini в настройках.`,
      });
    }

    const ai = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build",
        },
      },
    });

    // Format conversation contents
    const contents: any[] = [];
    if (Array.isArray(history)) {
      for (const h of history.slice(-6)) {
        if (h.role === "user" || h.role === "model") {
          contents.push({
            role: h.role,
            parts: [{ text: h.text }],
          });
        }
      }
    }
    contents.push({
      role: "user",
      parts: [{ text: message }],
    });

    const response = await ai.models.generateContent({
      model: "gemini-3.7-flash",
      contents,
      config: {
        systemInstruction: ALLIANCE_SYSTEM_INSTRUCTION,
        temperature: 0.7,
      },
    });

    const text = response.text || "Связь с командным пунктом установлена. Следуйте приказам штаба!";
    res.json({ reply: text });
  } catch (error: any) {
    console.error("AI Error:", error);
    res.status(500).json({
      error: "Ошибка связи со штабным советником",
      details: error.message,
    });
  }
});

