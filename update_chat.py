for day_id, template in chat_templates.items():
    pattern = r'(id:\s*"' + day_id + r'".*?shortChatTemplate:\s*)"[^"]*"'
    replacement = r'\1"' + template + r'"'
    content = re.sub(pattern, replacement, content, flags=re.DOTALL)

with open('src/data/allianceData.ts', 'w', encoding='utf-8') as f:
    f.write(content)
